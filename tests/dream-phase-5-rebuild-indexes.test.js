test('stageRebuildPlan: writes 5 staged artifacts in expected paths', async () => {
  const dir = await tmpDir();
  const dreamDir = path.join(dir, 'archive', 'dreams', '2026-05-10');
  await fs.mkdir(dreamDir, { recursive: true });
  const { plan } = await runRebuildIndexes({
    memoryRoot: dir, today: '2026-05-10',
    ...EMPTY_SUMMARIES, ...EMPTY_PLANS,
  });
  const { stagedFiles } = await stageRebuildPlan({ plan, dreamDir, today: '2026-05-10' });
  assert.equal(stagedFiles.length, 5);

  // 3 sweep-targeted .tmp files
  const tmpPaths = stagedFiles.filter(p => p.endsWith('.tmp'));
  assert.equal(tmpPaths.length, 3);
  assert.ok(tmpPaths.some(p => p.endsWith('staged/memory-index.md.tmp')));
  assert.ok(tmpPaths.some(p => p.endsWith('staged/pre-action.md.tmp')));
  assert.ok(tmpPaths.some(p => p.endsWith('staged/.dream-log.md.tmp')));

  // 2 archive-only files (live in archive/dreams/<date>/)
  assert.ok(stagedFiles.some(p => p.endsWith('dream-log-entry.md')));
  assert.ok(stagedFiles.some(p => p.endsWith('event.json')));

  // event.json round-trips as valid JSON
  const eventPath = stagedFiles.find(p => p.endsWith('event.json'));
  const ev = JSON.parse(await fs.readFile(eventPath, 'utf8'));
  assert.equal(ev.schema_version, '1.0.0');
});

