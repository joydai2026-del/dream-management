test('runRebuildIndexes: appends to existing .dream-log.md (preserving prior entries)', async () => {
  const dir = await tmpDir();
  await writeFile(path.join(dir, '.dream-log.md'), '# Dream Log\n\n## 2026-05-09 PASS\n\nprior entry\n');
  const { plan } = await runRebuildIndexes({
    memoryRoot: dir, today: '2026-05-10',
    ...EMPTY_SUMMARIES, ...EMPTY_PLANS,
  });
  assert.match(plan.dreamLog.content, /## 2026-05-09 PASS/);
  assert.match(plan.dreamLog.content, /## 2026-05-10/);
  // Order: prior entry first, new entry after
  const idx9 = plan.dreamLog.content.indexOf('2026-05-09');
  const idx10 = plan.dreamLog.content.indexOf('2026-05-10');
  assert.ok(idx9 < idx10);
});

