async function tmpDir() {
  return await fs.mkdtemp(path.join(os.tmpdir(), 'dream-p5-'));
}

async function writeFile(p, content) {
  await fs.mkdir(path.dirname(p), { recursive: true });
  await fs.writeFile(p, content);
}

