// Phase-5 REBUILD INDEXES.
//
// Per ARCHITECTURE.md § 3.2 + archive-schema.md § 2.5 / § 2.1, Phase 5
// produces five artifacts derived from the prior phases' plans + summaries:
//
//   1. memory-index.md         — warm-tier topic map (regenerated)
//   2. pre-action.md           — top-7 active patterns w/ action triggers
//   3. .dream-log.md           — append nightly human-readable run summary
//   4. archive/dreams/<date>/dream-log-entry.md
//                              — same human-readable summary, archived
//   5. archive/dreams/<date>/event.json
//                              — canonical machine-readable run record
//                                (per archive-schema § 2.5 schema)
//
// All five lands in `archive/dreams/<date>/staged/` per atomicity-contract
// § 2; the P5 sweep step (when wired) renames each `.tmp` to live.
//
// Phase 5 is read-only against the prior phase plans + a snapshot of the
// patterns/active directory; it does not re-run any classifier.

import { promises as fs } from 'node:fs';
import path from 'node:path';
import { atomicWrite } from '../atomic-write.js';
import { loadPatterns } from './load-patterns.js';

const SCHEMA_VERSION = '1.0.0';
const ISO_DATE_RE = /^\d{4}-\d{2}-\d{2}$/;
const PRE_ACTION_TOP_N = 7;

function escapeRegExp(s) { return String(s).replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

// ---- memory-index.md --------------------------------------------------

/**
 * Build the warm-tier memory index. Scans the live tree for hot/warm tier
 * files + cold-tier archive directories. Produces a markdown topic map.
 *
 * The format is a stable shape (deterministic file listing) so a diff
 * against the prior memory-index.md surfaces what's changed run-to-run.
 */
export async function buildMemoryIndex({ memoryRoot, today }) {
  const sections = [];
  sections.push(`# Memory Index`);
  sections.push('');
  sections.push(`Generated by /dream on ${today}. Schema ${SCHEMA_VERSION}.`);
  sections.push('');

  sections.push('## Hot tier');
  sections.push('');
  for (const rel of ['working-memory.md', 'identity.md', 'pre-action.md']) {
    const exists = await fileExists(path.join(memoryRoot, rel));
    sections.push(`- ${exists ? '✅' : '⚪'} \`${rel}\``);
  }

  const activeNames = (await readdirSafe(path.join(memoryRoot, 'patterns', 'active')))
    .filter(n => n.endsWith('.md')).sort();
  sections.push(`- patterns/active/ — ${activeNames.length} files`);

  sections.push('');
  sections.push('## Warm tier');
  sections.push('');
  for (const rel of ['corrections.md', 'session-index.md', 'memory-index.md', 'pattern-firing-log.md']) {
    const exists = await fileExists(path.join(memoryRoot, rel));
    sections.push(`- ${exists ? '✅' : '⚪'} \`${rel}\``);
  }

  const refNames = (await readdirSafe(path.join(memoryRoot, 'patterns', 'reference')))
    .filter(n => n.endsWith('.md')).sort();
  sections.push(`- patterns/reference/ — ${refNames.length} files`);

  sections.push('');
  sections.push('## Cold tier (archive/)');
  sections.push('');
  for (const sub of ['dreams', 'sessions', 'corrections', 'journals', 'next-session-prompts', 'firing-logs', 'patterns']) {
    const abs = path.join(memoryRoot, 'archive', sub);
    const entries = await readdirSafe(abs);
    sections.push(`- archive/${sub}/ — ${entries.length} entries`);
  }

  sections.push('');
  return sections.join('\n') + '\n';
}

// ---- pre-action.md ----------------------------------------------------

/**
 * Build the read-side checkpoint that the next session's memory-loader
 * surfaces. Top-N active patterns by `importance` (frontmatter), with
 * each rule's `action_trigger:` (or a fallback identifier line).
 *
 * The architecture's example shape (§ 2.3) is "BEFORE doing X, check Y".
 * Phase-5 v1 emits `<identifier>: <action>` lines; the prose framing is
 * left to the human curator (or a future LLM enhancer in P5+).
 */
export async function buildPreAction({ memoryRoot, today }) {
  const patterns = await loadPatterns(memoryRoot, 'active');
  // Sort by importance desc, then sightings desc, then alphabetical.
  patterns.sort((a, b) => {
    const ai = Number.isFinite(a.frontmatter?.importance) ? a.frontmatter.importance : 0;
    const bi = Number.isFinite(b.frontmatter?.importance) ? b.frontmatter.importance : 0;
    if (bi !== ai) return bi - ai;
    if (b.sightings !== a.sightings) return b.sightings - a.sightings;
    return a.name.localeCompare(b.name);
  });
  const top = patterns.slice(0, PRE_ACTION_TOP_N);

  const lines = [];
  lines.push(`# Pre-Action Rules`);
  lines.push('');
  lines.push(`Generated by /dream on ${today}. Top ${top.length} patterns by importance × sightings.`);
  lines.push(`Loaded by memory-loader at session start; cited by wrap-up's pattern-firing classifier.`);
  lines.push('');
  if (top.length === 0) {
    lines.push('_No active patterns yet. Pre-action.md will populate as patterns get promoted._');
    lines.push('');
    return lines.join('\n');
  }
  for (const p of top) {
    const trigger = (p.frontmatter?.action_trigger || p.frontmatter?.title || p.name)
      .toString().replace(/[\r\n]+/g, ' ').slice(0, 200);
    lines.push(`- **${p.name}** (importance ${p.frontmatter?.importance ?? '?'}, sightings ${p.sightings}): ${trigger}`);
    lines.push(`  - source: \`patterns/active/${p.name}.md\``);
  }
  lines.push('');
  return lines.join('\n');
}

// ---- dream-log entry --------------------------------------------------

/**
 * Render the human-readable run summary. Same content lands in two places
 * (the live `.dream-log.md` append and `archive/dreams/<date>/dream-log-entry.md`).
 */
export function renderDreamLogEntry({
  today,
  verdict,
  phase1Summary,
  phase2Summary,
  phase3Summary,
  phase4Summary,
  routePlan,
  prunePlan,
  datesPlan,
}) {
  const out = [];
  out.push(`## ${today} ${verdict}`);
  out.push('');
  out.push(`**Source signal**: journal=${phase1Summary.journalEntriesByBucket ? Object.values(phase1Summary.journalEntriesByBucket).reduce((s, n) => s + n, 0) : 0}, sessionMarkers=${phase1Summary.sessionMarkersByKind ? Object.values(phase1Summary.sessionMarkersByKind).reduce((s, n) => s + n, 0) : 0}.`);
  out.push('');

  out.push('**Insights / route**:');
  out.push(`- scored=${phase2Summary.scoredInsightCount} above-threshold=${phase2Summary.aboveThresholdCount}`);
  out.push(`- reinforced patterns: ${routePlan.reinforce.length}`);
  if (routePlan.reinforce.length > 0) {
    for (const r of routePlan.reinforce.slice(0, 5)) {
      out.push(`  - ${r.pattern} (sightings ${r.sightingsBefore}→${r.sightingsAfter})`);
    }
  }
  out.push(`- promotions: ${routePlan.promote.length}, declined: ${routePlan.declined.length}`);
  if (routePlan.removeReference?.length > 0) {
    out.push(`- reference removals planned: ${routePlan.removeReference.length}`);
  }
  out.push('');

  out.push('**Pruned**:');
  out.push(`- corrections archived: ${phase3Summary.correctionsArchivedBlocks} blocks (kept ${phase3Summary.correctionsKeptBlocks})`);
  out.push(`- session-index archived: ${phase3Summary.sessionIndexArchivedBlocks} blocks (kept ${phase3Summary.sessionIndexKeptBlocks})`);
  out.push(`- journal archived: ${phase3Summary.journalArchived}${phase3Summary.journalArchiveCollision ? ' (COLLISION — surface)' : ''}`);
  out.push(`- patterns demoted: ${phase3Summary.demotedCount}`);
  if (prunePlan.demotions.length > 0) {
    for (const d of prunePlan.demotions.slice(0, 5)) {
      out.push(`  - ${d.name}`);
    }
  }
  out.push('');

  out.push('**Dates + contradictions**:');
  out.push(`- relative-date rewrites: ${phase4Summary.totalReplacements} across ${phase4Summary.filesWithReplacements} files`);
  out.push(`- contradictions: ${phase4Summary.contradictionsStub ? 'STUB (detector deferred)' : phase4Summary.contradictionCount}`);
  if (phase4Summary.workingMemoryOverflowSkipped > 0) {
    out.push(`- ⚠️  working-memory.md overflow: rewrite would breach 80-line cap; skipped (${phase4Summary.workingMemoryOverflowSkipped})`);
  }
  out.push('');

  out.push('**Auditor**: pending (Stage A + Stage B run on the staged tree before sweep).');
  out.push('');
  return out.join('\n');
}

// ---- event.json -------------------------------------------------------

/**
 * Build the canonical machine-readable record per archive-schema § 2.5.
 * Consumed by the weekly digest generator + future cross-day analyses.
 */
export function buildEventJson({
  today,
  verdict,
  consumerName,
  gitTag,
  phase1Summary,
  routePlan,
  prunePlan,
  datesPlan,
  phase2Summary,
  phase3Summary,
  phase4Summary,
}) {
  return {
    schema_version: SCHEMA_VERSION,
    run_id: `${today}T03:00:00`,
    consumer_name: consumerName || 'unnamed-consumer',
    git_tag: gitTag || `dream/pre/${today}`,
    verdict,
    source_signal: {
      journal_entries_consumed: phase1Summary.journalEntriesByBucket
        ? Object.values(phase1Summary.journalEntriesByBucket).reduce((s, n) => s + n, 0) : 0,
      session_markers_extracted: phase1Summary.sessionMarkersByKind
        ? Object.values(phase1Summary.sessionMarkersByKind).reduce((s, n) => s + n, 0) : 0,
    },
    routed: {
      patterns_reinforced: routePlan.reinforce.map(r => ({
        pattern: r.pattern,
        sightings_after: r.sightingsAfter,
      })),
      patterns_promoted: routePlan.promote.map(p => ({
        slug: p.slug, importance: p.importance, journal_mentions: p.journalMentions,
      })),
      patterns_promotion_declined: routePlan.declined.map(d => ({
        slug: d.slug, reason: d.reason,
      })),
      reference_removals: (routePlan.removeReference || []).map(r => ({ slug: r.slug })),
    },
    pruned: {
      corrections_blocks_archived: phase3Summary.correctionsArchivedBlocks,
      corrections_blocks_kept: phase3Summary.correctionsKeptBlocks,
      session_index_blocks_archived: phase3Summary.sessionIndexArchivedBlocks,
      session_index_blocks_kept: phase3Summary.sessionIndexKeptBlocks,
      journals_archived: phase3Summary.journalArchived,
      journal_archive_collision: Boolean(phase3Summary.journalArchiveCollision),
      patterns_demoted: prunePlan.demotions.map(d => ({ name: d.name, reason: d.reason })),
    },
    dates: {
      files_rewritten: phase4Summary.filesWithReplacements,
      total_replacements: phase4Summary.totalReplacements,
      working_memory_overflow_skipped: phase4Summary.workingMemoryOverflowSkipped,
      pre_staged_hits: phase4Summary.preStagedHits ?? 0,
    },
    contradictions: {
      stub: phase4Summary.contradictionsStub === true,
      surfaced: datesPlan.contradictions || [],
    },
    audit: {
      stage_a: { verdict: 'pending', findings: [] },
      stage_b: { verdict: 'pending', findings: [], model: null },
    },
  };
}

// ---- runRebuild + stagePlan ------------------------------------------

/**
 * Build the Phase-5 plan from collected outputs of phases 1-4.
 *
 * @param {object} opts
 * @param {string} opts.memoryRoot
 * @param {string} opts.today                YYYY-MM-DD
 * @param {string} [opts.consumerName]
 * @param {string} [opts.gitTag]
 * @param {string} [opts.verdict]            default 'PASS-TENTATIVE' (audit pending)
 * @param {object} opts.phase1Summary
 * @param {object} opts.phase2Summary
 * @param {object} opts.phase3Summary
 * @param {object} opts.phase4Summary
 * @param {object} opts.routePlan
 * @param {object} opts.prunePlan
 * @param {object} opts.datesPlan
 * @returns {Promise<{plan: RebuildPlan, summary}>}
 */
export async function runRebuildIndexes(opts) {
  const {
    memoryRoot, today,
    consumerName, gitTag,
    verdict = 'PASS-TENTATIVE',
    phase1Summary = {}, phase2Summary = {}, phase3Summary = {}, phase4Summary = {},
    routePlan = { reinforce: [], promote: [], declined: [], removeReference: [] },
    prunePlan = { corrections: { archive: [] }, sessionIndex: { archive: [] }, journal: {}, demotions: [] },
    datesPlan = { byFile: [], contradictions: [] },
  } = opts || {};
  if (!memoryRoot) throw new Error('runRebuildIndexes: memoryRoot required');
  if (!today) throw new Error('runRebuildIndexes: today required');
  if (!ISO_DATE_RE.test(today)) {
    throw new Error(`runRebuildIndexes: today must match YYYY-MM-DD; got '${today}'`);
  }

  const memoryIndexContent = await buildMemoryIndex({ memoryRoot, today });
  const preActionContent = await buildPreAction({ memoryRoot, today });
  const dreamLogEntryContent = renderDreamLogEntry({
    today, verdict,
    phase1Summary, phase2Summary, phase3Summary, phase4Summary,
    routePlan, prunePlan, datesPlan,
  });
  const eventJsonObj = buildEventJson({
    today, verdict, consumerName, gitTag,
    phase1Summary, routePlan, prunePlan, datesPlan,
    phase2Summary, phase3Summary, phase4Summary,
  });

  // Read existing .dream-log.md (if any) and produce the appended version.
  // Append-style files travel through the staged-tree by storing the FULL
  // resulting content; the sweep renames it onto live.
  const liveDreamLog = await readIfExists(path.join(memoryRoot, '.dream-log.md'));
  const dreamLogAppended = (liveDreamLog || '# Dream Log\n\n') + dreamLogEntryContent;

  const plan = {
    today,
    memoryIndex: { content: memoryIndexContent },
    preAction: { content: preActionContent },
    dreamLogEntry: { content: dreamLogEntryContent },
    eventJson: { content: JSON.stringify(eventJsonObj, null, 2) + '\n' },
    dreamLog: { content: dreamLogAppended },
  };
  const summary = {
    memoryIndexLines: memoryIndexContent.split('\n').length,
    preActionLines: preActionContent.split('\n').length,
    dreamLogEntryLines: dreamLogEntryContent.split('\n').length,
    eventJsonBytes: plan.eventJson.content.length,
    verdict,
  };
  return { plan, summary };
}

/**
 * Stage every Phase-5 artifact under archive/dreams/<date>/staged/.
 *
 * memory-index.md and pre-action.md sweep onto live. dream-log-entry.md and
 * event.json live forever inside `archive/dreams/<date>/`. .dream-log.md
 * is an append-mode file at memory-root; the staged version is the full
 * appended content (ready for atomic rename onto live).
 */
export async function stageRebuildPlan(args) {
  const { plan, dreamDir, today } = args || {};
  if (!plan) throw new Error('stageRebuildPlan: plan required');
  if (!dreamDir) throw new Error('stageRebuildPlan: dreamDir required');
  if (!today) throw new Error('stageRebuildPlan: today required');

  const stagedRoot = path.join(dreamDir, 'staged');
  const stagedFiles = [];

  await fs.mkdir(stagedRoot, { recursive: true });

  // Hot/warm-tier files staged for sweep onto live.
  for (const [rel, payload] of [
    ['memory-index.md', plan.memoryIndex.content],
    ['pre-action.md', plan.preAction.content],
    ['.dream-log.md', plan.dreamLog.content],
  ]) {
    const stagedPath = path.join(stagedRoot, `${rel}.tmp`);
    await fs.mkdir(path.dirname(stagedPath), { recursive: true });
    await atomicWrite(stagedPath, payload);
    stagedFiles.push(stagedPath);
  }

  // Per-night archives. These live forever under archive/dreams/<date>/.
  // They're written DIRECTLY (not via *.tmp) because they don't sweep onto
  // live — they ARE the canonical archive. Atomic-write still applies.
  const dreamLogEntryPath = path.join(dreamDir, 'dream-log-entry.md');
  await atomicWrite(dreamLogEntryPath, plan.dreamLogEntry.content);
  stagedFiles.push(dreamLogEntryPath);

  const eventJsonPath = path.join(dreamDir, 'event.json');
  await atomicWrite(eventJsonPath, plan.eventJson.content);
  stagedFiles.push(eventJsonPath);

  return { stagedFiles };
}

// ---- helpers ----------------------------------------------------------

async function fileExists(abs) {
  try { await fs.access(abs); return true; } catch { return false; }
}

async function readdirSafe(abs) {
  try { return await fs.readdir(abs); } catch { return []; }
}

async function readIfExists(abs) {
  try { return await fs.readFile(abs, 'utf8'); }
  catch (e) { if (e.code === 'ENOENT') return null; throw e; }
}

